"""Доменный корректор распознанной русской речи.

Первый реальный звонок через движок (03.09.2026, c_2a11d883a054) показал:
русский слух не знает слов нашего же мира. «На иврите» трижды пришло как
«на игри» / «игритии», «на русском» — как «на руском», и переводчик из этого
честно сделал «ברוש» (кипарис). Модель не переучить за вечер; ослышки на
СВОИ ЖЕ слова чинятся дешёвой заменой до перевода.

Правила применяются к каждой гипотезе СТТ одинаково (и к частичным, и к
финалам) — чанкер сравнивает гипотезы между собой, и правка обязана быть
детерминированной, иначе LocalAgreement увидит «изменившееся» слово.
"""

from __future__ import annotations

import re

# Пары «как слышится → как говорилось». Только высокоуверенные ослышки
# доменных слов: обычную речь не трогаем, чтобы не чинить здоровое.
_RU_RULES: tuple[tuple[re.Pattern[str], str], ...] = tuple(
    (re.compile(pattern, re.IGNORECASE), repl)
    for pattern, repl in [
        # «иврит» во всех падежах слух калечит чаще всего
        (r"\bна игр[а-яё]*\b", "на иврите"),
        (r"\bигрити[а-яё]*\b", "иврите"),
        (r"\bна еврите\b", "на иврите"),
        (r"\bна и врите\b", "на иврите"),
        (r"\bиврити\b", "иврите"),
        # одиночная «с» теряется
        (r"\bруском\b", "русском"),
        (r"\bруский\b", "русский"),
        # имя продукта
        (r"\bсейм ?войс\b", "SameVoice"),
        (r"\bсаме ?войс\b", "SameVoice"),
    ]
)


def correct_stt_text(text: str, lang: str) -> str:
    """Поправить доменные ослышки; чужие языки возвращаются как есть."""
    if lang != "ru" or not text:
        return text
    out = text
    for pattern, repl in _RU_RULES:
        out = pattern.sub(repl, out)
    return out
