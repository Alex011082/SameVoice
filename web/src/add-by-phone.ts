import { addByPhoneErrorText } from './errors';

/**
 * Что написать под формой «добавить по номеру».
 *
 * Отдельный модуль ради одной фразы — потому что фраза и есть предмет спора.
 * Сервер отвечает одинаково и на номер, за которым есть профиль, и на номер,
 * за которым никого нет: ручка, которая различает эти два случая, становится
 * справочником «кто здесь есть», а спрашивать её можно по любому номеру. Если
 * бы экран написал «такого номера у нас нет» или «Борис добавлен», он бы вернул
 * ровно ту утечку, которую сервер только что не допустил, — и вернул бы её
 * молча, потому что в backend'е всё было бы правильно.
 *
 * Поэтому подтверждение — условное. Оно не врёт («готово» — правда: запрос
 * принят) и ничего не сообщает о чужом номере. Кто на самом деле появился в
 * списке, человек видит в самом списке — списке СВОИХ контактов, а не в ответе
 * на запрос про чужой номер.
 */
export const ADD_BY_PHONE_DONE =
  'Готово. Если у этого номера есть профиль, контакт уже в списке.';

export interface AddByPhoneStatus {
  text: string;
  tone: 'ok' | 'error';
}

export function addByPhoneDone(): AddByPhoneStatus {
  return { text: ADD_BY_PHONE_DONE, tone: 'ok' };
}

export function addByPhoneFailed(err: unknown): AddByPhoneStatus {
  return { text: addByPhoneErrorText(err), tone: 'error' };
}
