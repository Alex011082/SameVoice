/**
 * `?me=` — подсказка, а не вход.
 *
 * До 31.08.2026 личность клиента была параметром адресной строки: кто держал
 * ссылку `?me=<userId>`, тот и был этим человеком, и каждая ручка
 * `/api/users/:userId/...` верила пути. Параметр остался — по нему удобно
 * открыть нужный профиль закладкой, и на нём же держится инвайт-ссылка на
 * звонок, — но решать он больше ничего не может.
 *
 * ПОЧЕМУ ЭТО НЕ ДЫРА, одной строкой: сервер этот параметр не читает вовсе.
 * Личность приходит подписанной сессией, каждая ручка сверяет userId с ней и
 * отвечает 403 на чужой, так что подставить сюда чужой id — то же самое, что
 * набрать его в адресной строке браузера соседа: экран, может, и попросят, а
 * данные не отдадут. Функция ниже делает это правилом клиента, а не привычкой:
 * подсказка НИКОГДА не становится ответом, она может только не совпасть.
 */
export interface ResolvedIdentity {
  /** Кем клиент работает на самом деле. null — не вошли. */
  userId: string | null;
  /**
   * Профиль, названный в ссылке и НЕ совпавший с сессией. Не ошибка: так
   * выглядит чужая инвайт-ссылка или закладка от прошлого входа. Экран должен
   * сказать об этом вслух, иначе человек будет уверен, что смотрит на профиль
   * из ссылки.
   */
  ignoredHint: string | null;
}

export function resolveIdentity(
  hint: string | null,
  sessionUserId: string | null,
): ResolvedIdentity {
  if (sessionUserId === null) return { userId: null, ignoredHint: hint };
  return {
    userId: sessionUserId,
    ignoredHint: hint !== null && hint !== sessionUserId ? hint : null,
  };
}
